#!/usr/bin/env python3
"""EarthBound asset index: committed headers + earthbound_assets.dat packer.

The ROM-derived asset bytes ship as earthbound_assets.dat, separate from the
binary, so EarthBound.bin and earthbound.ro build without the ROM. The binary
only needs the asset *ids*, which live in committed headers under src/gen/.

  gen-headers   ebtools outputs -> src/gen/{asset_ids.h, embedded_assets.h,
                eb_asset_list.txt, items_generated.h, music_generated.h}.
                Rerun after a submodule bump (needs the ROM).
  check         fail if src/gen/eb_asset_list.txt no longer matches what
                ebtools embed-registry produced (stale committed headers).
  pack          eb_asset_list.txt + ebtools outputs -> earthbound_assets.dat

eb_asset_list.txt is the layout contract: line i names the file that becomes
asset id i, as `packed/<path>` (under ebtools pack-all's output dir) or
`bin/<path>` (under the submodule's asm/bin). Its CRC32 is compiled into the
binary and stored in the .dat header, so a .dat built for another asset list
is refused at boot.

earthbound_assets.dat (little-endian):

  0   u32 magic 'EBA1'
  4   u32 asset count
  8   u32 CRC32 of eb_asset_list.txt
  12  u32 file length
  16  count x { u32 offset, u32 size }   offsets from the start of the file
      asset bytes, each starting on a 16-byte boundary
"""

import argparse
import re
import sys
import zlib
from pathlib import Path

MAGIC = 0x31414245  # "EBA1"
HEADER_SIZE = 16
ALIGN = 16

GEN_NOTE = "/* Generated by scripts/eb_assets.py gen-headers - do not edit */\n"


def read_layout(gen_dir: Path, eb_dir: Path) -> list[str]:
    """Asset files in enum order, as eb_asset_list.txt entries."""
    ids_h = (gen_dir / "asset_ids.h").read_text()
    enum_body = re.search(r"typedef enum \{(.*?)\} AssetId;", ids_h, re.S).group(1)
    ids = re.findall(r"^\s*(ASSET_\w+),", enum_body, re.M)

    inc = (gen_dir / "embedded_assets.inc.c").read_text()
    sym_path = dict(re.findall(r'INCBIN\((\w+), "([^"]+)"\)', inc))
    arr = (gen_dir / "embedded_assets_array.c").read_text()
    id_sym = dict(re.findall(r"\[(ASSET_\w+)\] = \{ (\w+)Data,", arr))

    packed_dir = (gen_dir / "packed_assets").resolve()
    bin_dir = (eb_dir / "asm" / "bin").resolve()
    layout = []
    for asset_id in ids:
        path = Path(sym_path[id_sym[asset_id]]).resolve()
        if path.is_relative_to(packed_dir):
            layout.append("packed/" + path.relative_to(packed_dir).as_posix())
        elif path.is_relative_to(bin_dir):
            layout.append("bin/" + path.relative_to(bin_dir).as_posix())
        else:
            sys.exit(f"eb_assets: {asset_id} comes from unexpected path {path}")
    return layout


def layout_text(layout: list[str]) -> str:
    return "".join(entry + "\n" for entry in layout)


def gen_asset_ids_h(gen_dir: Path, layout_crc: int) -> str:
    """Upstream's asset_ids.h with every accessor routed through
    embedded_assets[], which app_main_earthbound fills from the .dat header.

    Upstream's direct-access macros name INCBIN symbols and its per-family
    tables are link-time pointer arrays; neither exists without the ROM."""
    src = (gen_dir / "asset_ids.h").read_text()
    head, rest = src.split("/* Direct-access macros", 1)
    head = head.replace('#include "embedded_assets_decl.h"\n', "")
    head = head.replace(
        "/* Auto-generated by ebtools embed-registry - do not edit */\n",
        GEN_NOTE + "/* (from ebtools embed-registry's asset_ids.h) */\n")

    out = [head]
    out.append(f"#define EB_ASSET_LAYOUT_CRC 0x{layout_crc:08X}u\n\n")
    out.append("/* Direct access, through the runtime index (see embedded_assets.h) */\n")
    direct = re.findall(r"^#define (ASSET_\w+)_DATA \(\(const uint8_t \*\)\w+\)$", rest, re.M)
    for asset_id in direct:
        out.append(f"#define {asset_id}_DATA ((const uint8_t *)embedded_assets[{asset_id}].data)\n")
        out.append(f"#define {asset_id}_SIZE ((size_t)*embedded_assets[{asset_id}].size_ptr)\n")

    aliases = re.findall(r"^#define (ASSET_\w+) (ASSET_\w+)$", rest, re.M)
    out.append("\n/* Locale-resolved aliases */\n")
    out.extend(f"#define {a} {b}\n" for a, b in aliases)

    # Families. Upstream's FAM(n) id macros carry over verbatim; FAM_DATA(n)
    # indexes upstream's link-time pointer table by position, which becomes
    # an id lookup: arithmetic when the table is a contiguous id range, else
    # a const id table.
    arr = (gen_dir / "embedded_assets_array.c").read_text()
    id_sym = {sym: asset_id for asset_id, sym in
              re.findall(r"\[(ASSET_\w+)\] = \{ (\w+)Data,", arr)}
    enum_body = re.search(r"typedef enum \{(.*?)\} AssetId;", src, re.S).group(1)
    enum_ids = re.findall(r"^\s*(ASSET_\w+),", enum_body, re.M)
    enum_index = {name: i for i, name in enumerate(enum_ids)}
    tables = dict(re.findall(r"AssetFamilyEntry (asset_family_\w+)\[\d+\] = \{(.*?)\};", arr, re.S))
    declared = re.findall(r"^extern const AssetFamilyEntry (asset_family_\w+)\[(\d+)\];\n"
                          r"#define (ASSET_\w+)_DATA\(n\)", rest, re.M)
    if len(declared) != len(tables):
        sys.exit(f"eb_assets: parsed {len(declared)} family declarations but {len(tables)} tables")

    out.append("\n/* Per-family lookup (runtime-indexed) */\n")
    out.extend(line + "\n" for line in re.findall(r"^#define ASSET_\w+\(n\) .*$", rest, re.M)
               if not re.match(r"#define ASSET_\w+_(DATA|SIZE)\(n\)", line))
    for table, count, fam in declared:
        ids = [id_sym[sym] for sym in re.findall(r"\{ (\w+)Data,", tables[table])]
        if len(ids) != int(count):
            sys.exit(f"eb_assets: {table} has {len(ids)} entries, declared {count}")
        if all(enum_index[i] == enum_index[ids[0]] + n for n, i in enumerate(ids)):
            index = f"({ids[0]} + (n))"
        else:
            out.append(f"static const uint16_t {table}_ids[{count}] __attribute__((unused)) = {{\n")
            out.extend(f"    {i},\n" for i in ids)
            out.append("};\n")
            index = f"{table}_ids[n]"
        out.append(f"#define {fam}_DATA(n) ((const uint8_t *)embedded_assets[{index}].data)\n")
        out.append(f"#define {fam}_SIZE(n) ((size_t)*embedded_assets[{index}].size_ptr)\n")

    out.append("\n#endif /* ASSET_IDS_H */\n")
    return "".join(out)


EMBEDDED_ASSETS_H = GEN_NOTE + """\
#ifndef EMBEDDED_ASSETS_H
#define EMBEDDED_ASSETS_H

#include "asset_ids.h"

/* Same shape as ebtools' AssetEntry, so data/assets.h's ASSET_DATA/ASSET_SIZE
 * work unchanged. Filled at boot from earthbound_assets.dat's header
 * (eb_assets_load in main_earthbound.c): data points into the cached .dat and
 * size_ptr at the size word in its header. */
typedef struct {
    const unsigned char *data;
    const unsigned int *size_ptr;
} AssetEntry;

extern AssetEntry embedded_assets[ASSET_COUNT];

#endif /* EMBEDDED_ASSETS_H */
"""


def cmd_gen_headers(args) -> None:
    layout = read_layout(args.gen_dir, args.eb_dir)
    text = layout_text(layout)
    crc = zlib.crc32(text.encode())
    out = args.out_dir
    out.mkdir(parents=True, exist_ok=True)
    (out / "eb_asset_list.txt").write_text(text)
    (out / "asset_ids.h").write_text(gen_asset_ids_h(args.gen_dir, crc))
    (out / "embedded_assets.h").write_text(EMBEDDED_ASSETS_H)
    for name in ("items_generated.h", "music_generated.h"):
        (out / name).write_bytes((args.gen_dir / name).read_bytes())
    print(f"eb_assets: {len(layout)} assets, layout CRC 0x{crc:08X} -> {out}")


def cmd_check(args) -> None:
    """The .dat must match what the binary was compiled against: the asset
    ids (src/gen/) and the dialogue offsets (upstream's committed text_refs.h)."""
    layout = layout_text(read_layout(args.gen_dir, args.eb_dir))
    expected = {
        "eb_asset_list.txt": layout,
        "asset_ids.h": gen_asset_ids_h(args.gen_dir, zlib.crc32(layout.encode())),
        "embedded_assets.h": EMBEDDED_ASSETS_H,
        "items_generated.h": (args.gen_dir / "items_generated.h").read_text(),
        "music_generated.h": (args.gen_dir / "music_generated.h").read_text(),
    }
    stale = [name for name, text in expected.items()
             if (args.out_dir / name).read_text() != text]
    if stale:
        sys.exit(f"eb_assets: src/gen/ is stale for this submodule ({', '.join(stale)}). "
                 "Run `make gen-headers` and commit src/gen/.")
    text_refs = args.eb_dir / "src" / "data" / "text_refs.h"
    if (args.gen_dir / "text_refs.h").read_text() != text_refs.read_text():
        sys.exit(f"eb_assets: ebtools pack-all's text_refs.h differs from {text_refs}: "
                 "the dialogue blob wouldn't match the offsets compiled into the binary.")


def pack_dat(blobs: list[bytes], layout_crc: int) -> bytes:
    """Assets in id order -> earthbound_assets.dat."""
    offset = HEADER_SIZE + 8 * len(blobs)
    table = bytearray()
    body = bytearray()
    for blob in blobs:
        pad = -(offset + len(body)) % ALIGN
        body += bytes(pad)
        table += (offset + len(body)).to_bytes(4, "little") + len(blob).to_bytes(4, "little")
        body += blob
    total = offset + len(body)
    header = b"".join(v.to_bytes(4, "little") for v in (MAGIC, len(blobs), layout_crc, total))
    return bytes(header + table + body)


def cmd_pack(args) -> None:
    layout = args.list.read_text().splitlines()
    crc = zlib.crc32(args.list.read_bytes())
    roots = {"packed": args.packed_dir, "bin": args.bin_dir}

    blobs = []
    for entry in layout:
        kind, rel = entry.split("/", 1)
        blobs.append((roots[kind] / rel).read_bytes())

    dat = pack_dat(blobs, crc)
    args.out.write_bytes(dat)
    print(f"eb_assets: {args.out} ({len(dat)} bytes, {len(blobs)} assets)")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = parser.add_subparsers(dest="cmd", required=True)

    for name in ("gen-headers", "check"):
        p = sub.add_parser(name)
        p.add_argument("--gen-dir", type=Path, required=True, help="ebtools embed-registry output dir")
        p.add_argument("--eb-dir", type=Path, required=True, help="external/earthbound")
        p.add_argument("--out-dir", type=Path, required=True, help="committed headers (src/gen)")

    p = sub.add_parser("pack")
    p.add_argument("--list", type=Path, required=True, help="src/gen/eb_asset_list.txt")
    p.add_argument("--packed-dir", type=Path, required=True)
    p.add_argument("--bin-dir", type=Path, required=True)
    p.add_argument("--out", type=Path, required=True)

    args = parser.parse_args()
    {"gen-headers": cmd_gen_headers, "check": cmd_check, "pack": cmd_pack}[args.cmd](args)


if __name__ == "__main__":
    main()
